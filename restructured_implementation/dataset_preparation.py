import numpy as np

def load_ts(path):
    """Lee un .ts multivariado. Devuelve X (ventanas, canales, muestras) e y (BPM)."""
    X, y, in_data = [], [], False
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            if not in_data:
                in_data = line.lower().startswith("@data")
                continue
            *dims, target = line.split(":")
            X.append([[np.nan if v == "?" else float(v) for v in d.split(",")] for d in dims])
            y.append(float(target))
    return np.asarray(X), np.asarray(y)


#the dataset was generated by splitting longer recordings into overlapping intervals, to insure no data leakage occurs
#a function is defined to identify windows that are for a single person

def split_participants(
    X: np.ndarray, step: int = 250, tol: float = 1e-3
) -> list[list[int]]:
    """Partitions sequentially ordered sliding windows into lists of indices per participant."""
    overlap = X.shape[-1] - step
    matches = np.all(
        np.isclose(X[:-1, ..., step:], X[1:, ..., :overlap], atol=tol, equal_nan=True),
        axis=tuple(range(1, X.ndim)),
    )
    return [
        grp.tolist()
        for grp in np.split(np.arange(len(X)), np.where(~matches)[0] + 1)
    ]

