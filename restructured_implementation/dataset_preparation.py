"""
Dataset preparation and Subject-Wise Group K-Fold partitioning module.

Handles:
1. Loading multivariate .ts files into individual 5D windows of shape (n_windows, 5, 1000)
   and ground-truth heart rate targets y of shape (n_windows,).
2. Identifying recording session / participant boundaries via temporal overlap matching
   (`split_participants`) without merging windows into longer sequences.
3. Subject-Wise Group K-Fold cross-validation splitting (`subject_wise_group_kfold`)
   using scikit-learn's `GroupKFold` to prevent data leakage across windows from the
   same subject.
"""

import numpy as np

try:
    from sklearn.model_selection import GroupKFold
except ImportError:
    GroupKFold = None

# Sampling frequency (Hz), window length (8 s = 1000 samples), and stride (2 s = 250 samples)
FS: int = 125
WIN: int = 1000
STEP: int = 250
CH_NAMES: list[str] = ["ppg1", "ppg2", "accx", "accy", "accz"]


def load_ts(path: str) -> tuple[np.ndarray, np.ndarray]:
    """Read a multivariate .ts file and return X (windows, channels, samples) and y (BPM).

    Parameters
    ----------
    path : str
        Path to the .ts dataset file (e.g., 'IEEEPPG_TRAIN.ts' or 'IEEEPPG_TEST.ts').

    Returns
    -------
    X : np.ndarray
        5-dimensional signal windows of shape (n_windows, 5, 1000),
        where channels are [ppg1, ppg2, accx, accy, accz].
    y : np.ndarray
        Ground-truth heart rate in BPM for each window, shape (n_windows,).
    """
    X, y, in_data = [], [], False
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            if not in_data:
                in_data = line.lower().startswith("@data")
                continue
            *dims, target = line.split(":")
            X.append([[np.nan if v == "?" else float(v) for v in d.split(",")] for d in dims])
            y.append(float(target))
    return np.asarray(X, dtype=float), np.asarray(y, dtype=float)


def split_participants(
    X: np.ndarray, step: int = STEP, tol: float = 1e-3
) -> list[list[int]]:
    """Partition sequentially ordered sliding windows into lists of indices per participant.

    The dataset was generated by splitting longer recordings into 8 s windows with a 2 s step
    (6 s overlap = 750 samples). Matching the 750-sample overlap identifies which windows
    originate from the same recording session / subject without merging them.

    Parameters
    ----------
    X : np.ndarray
        Windowed dataset array of shape (n_windows, 5, 1000).
    step : int, default=250
        Step size in samples between consecutive overlapping windows.
    tol : float, default=1e-3
        Absolute tolerance for matching overlapping segments.

    Returns
    -------
    list[list[int]]
        List of window index lists, one list per participant/recording session.
    """
    overlap = X.shape[-1] - step
    matches = np.all(
        np.isclose(X[:-1, ..., step:], X[1:, ..., :overlap], atol=tol, equal_nan=True),
        axis=tuple(range(1, X.ndim)),
    )
    return [
        grp.tolist()
        for grp in np.split(np.arange(len(X)), np.where(~matches)[0] + 1)
    ]


def get_participant_groups(
    X: np.ndarray, step: int = STEP, tol: float = 1e-3
) -> np.ndarray:
    """Assign a discrete participant/session group ID to each individual window.

    Returns
    -------
    groups : np.ndarray
        Integer array of shape (n_windows,) where `groups[i]` is the participant ID
        (0, 1, ..., n_participants - 1) for window `i`.
    """
    participant_lists = split_participants(X, step=step, tol=tol)
    groups = np.empty(len(X), dtype=int)
    for group_id, indices in enumerate(participant_lists):
        groups[indices] = group_id
    return groups


def subject_wise_group_kfold(
    X: np.ndarray,
    n_splits: int = 5,
    groups: np.ndarray | None = None,
    step: int = STEP,
    tol: float = 1e-3,
) -> list[tuple[np.ndarray, np.ndarray]]:
    """Partition dataset windows into Group K-Fold splits strictly by participant ID.

    Guarantees that all windows from a given recording session / subject are assigned
    exclusively to either the training set or the validation set in every fold,
    preventing any data leakage from overlapping windows while keeping each window
    as an independent sample.

    Parameters
    ----------
    X : np.ndarray
        Windowed dataset array of shape (n_windows, 5, 1000).
    n_splits : int, default=5
        Number of cross-validation folds `K` (must be <= number of participants).
    groups : np.ndarray, optional
        Precomputed participant group IDs of shape (n_windows,). If None, inferred
        automatically via `get_participant_groups(X)`.

    Returns
    -------
    splits : list[tuple[np.ndarray, np.ndarray]]
        List of `n_splits` tuples `(train_window_indices, val_window_indices)`.
    """
    if groups is None:
        groups = get_participant_groups(X, step=step, tol=tol)
    else:
        groups = np.asarray(groups, dtype=int)

    unique_groups, group_counts = np.unique(groups, return_counts=True)
    n_groups = len(unique_groups)
    if n_splits > n_groups:
        raise ValueError(
            f"Cannot have n_splits={n_splits} greater than the number of participants ({n_groups})."
        )

    if GroupKFold is not None:
        gkf = GroupKFold(n_splits=n_splits)
        return [(train_idx, val_idx) for train_idx, val_idx in gkf.split(X, groups=groups)]

    # Fallback balanced greedy group assignment (identical to scikit-learn's GroupKFold)
    sorted_order = np.argsort(group_counts)[::-1]
    sorted_groups = unique_groups[sorted_order]
    sorted_counts = group_counts[sorted_order]

    samples_per_fold = np.zeros(n_splits, dtype=int)
    group_to_fold = {}
    for g, count in zip(sorted_groups, sorted_counts):
        lightest_fold = int(np.argmin(samples_per_fold))
        group_to_fold[g] = lightest_fold
        samples_per_fold[lightest_fold] += count

    window_fold_ids = np.array([group_to_fold[g] for g in groups], dtype=int)
    all_indices = np.arange(len(X))

    splits = []
    for k in range(n_splits):
        val_mask = window_fold_ids == k
        splits.append((all_indices[~val_mask], all_indices[val_mask]))
    return splits
